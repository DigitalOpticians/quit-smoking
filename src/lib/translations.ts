const italian = new Map(Object.entries(english).map(([it, en]) => [en, it]));

export function translate(
  message: string,
  locale: Locale,
  values?: Record<string, string | number>,
) {
  const source = Object.hasOwn(english, message)
    ? message
    : (italian.get(message) ?? message);
  const text = locale === "en" ? (english[source] ?? source) : source;
  return text.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    String(values?.[key] ?? placeholder),
  );
}
